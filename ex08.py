# Leia um número inteiro e informe se ele é positivo ou negativo. Neste exercício, considere o zero como 
# positivo.

#Entrada de dados do usuário. Permitido apenas números inteiros
numero = int(input("Digite um número inteiro: "))

#Lógica de teste: SE o número for maoir que 0 o resultado é positivo, caso contrário é negativo.
if numero > 0:
    print("Seu número é positivo!")

else:
    print("Seu número é negativo!")


    
